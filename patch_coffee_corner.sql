-- ============================================================================
-- كوفي كورنر (COFFEE CORNER) — قسم مشروبات مستقل جوه تطبيق صالون أبو يوسف
-- ============================================================================
-- مبادئ التصميم:
--  1) جداول مستقلة (cafe_*): المشروب عمره ما بيدخل في invoices.total، فعمولة الحلاق
--     والمساعد والتارجت ونقاط الولاء والخصومات وكل تقارير الصالون ما بتتأثرش.
--  2) الدرج واحد: مبيعات الكوفي ومصروفاته ومشترياته المدفوعة من الدرج بتتضاف جوه
--     day_figures / range_figures، فالجرد وقفل اليوم والتقارير الحالية تفضل متسقة.
--  3) كل الكتابة من خلال دوال (SECURITY DEFINER) بصلاحيات متحققة جوه القاعدة.
--     مفيش أي سياسة INSERT/UPDATE/DELETE مباشرة على الجداول.
--  4) آمن للتشغيل أكتر من مرة (idempotent). مفيش حذف ولا تعديل لأي بيانات موجودة.
--     التعديلات على دوال موجودة: day_figures و range_figures (بتتغلّف)،
--     admin_void_invoice و admin_set_date (بتتضاف لهم أسطر)، وعمود cafe جديد في open_invoices.
-- ============================================================================

-- ---------------------------------------------------------------- الجداول
create table if not exists cafe_products (
  id          bigint generated by default as identity primary key,
  name        text not null check (btrim(name) <> ''),
  price       numeric(10,2) not null check (price >= 0),
  cost        numeric(10,2) not null default 0 check (cost >= 0),
  track_stock boolean not null default false,
  stock       integer not null default 0,
  min_stock   integer not null default 0 check (min_stock >= 0),
  active      boolean not null default true,
  sort        integer not null default 0,
  created_at  timestamptz not null default now(),
  constraint cafe_products_stock_ok check (stock >= 0)
);

create table if not exists cafe_sales (
  id             bigint generated by default as identity primary key,
  invoice_id     bigint references invoices(id) on delete cascade,   -- لو لزبون صالون
  payment_method text not null check (payment_method in ('cash','card','wallet')),
  total          numeric(10,2) not null default 0 check (total >= 0),
  status         text not null default 'paid' check (status in ('paid','void')),
  note           text,
  created_by     uuid,
  created_at     timestamptz not null default now(),
  voided_at      timestamptz,
  voided_by      uuid,
  void_reason    text
);
create index if not exists cafe_sales_created_idx on cafe_sales(created_at);
create index if not exists cafe_sales_invoice_idx on cafe_sales(invoice_id);

create table if not exists cafe_sale_items (
  id         bigint generated by default as identity primary key,
  sale_id    bigint not null references cafe_sales(id) on delete cascade,
  product_id bigint references cafe_products(id) on delete set null,
  name       text not null,
  qty        integer not null check (qty > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  unit_cost  numeric(10,2) not null default 0 check (unit_cost >= 0)   -- التكلفة وقت البيع
);
create index if not exists cafe_sale_items_sale_idx on cafe_sale_items(sale_id);

create table if not exists cafe_purchases (
  id            bigint generated by default as identity primary key,
  bought_on     date not null,
  kind          text not null check (kind in ('stock','supplies')),
  supplier_name text,
  total         numeric(10,2) not null check (total > 0),
  paid_from     text not null check (paid_from in ('drawer','other')),
  note          text,
  created_by    uuid,
  created_at    timestamptz not null default now()
);

create table if not exists cafe_purchase_items (
  id          bigint generated by default as identity primary key,
  purchase_id bigint not null references cafe_purchases(id) on delete cascade,
  product_id  bigint references cafe_products(id) on delete set null,
  name        text not null,
  qty         numeric(12,2) not null check (qty > 0),
  unit_cost   numeric(10,2) not null check (unit_cost >= 0)
);

create table if not exists cafe_expenses (
  id          bigint generated by default as identity primary key,
  spent_on    date not null,
  category    text not null check (btrim(category) <> ''),
  amount      numeric(10,2) not null check (amount > 0),
  note        text,
  paid_from   text not null default 'drawer' check (paid_from in ('drawer','other')),
  purchase_id bigint references cafe_purchases(id) on delete cascade,
  created_by  uuid,
  created_at  timestamptz not null default now()
);

create table if not exists cafe_stock_movements (
  id         bigint generated by default as identity primary key,
  product_id bigint references cafe_products(id) on delete set null,
  qty        integer not null,
  reason     text not null,
  created_by uuid,
  created_at timestamptz not null default now()
);

