-- ---------------------------------------------------------------- دوال مساعدة داخلية
create or replace function cafe_pay_ok(p_method text) returns void
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if p_method is null or p_method not in ('cash','card','wallet') then raise exception 'طريقة دفع غير مدعومة'; end if;
  if p_method = 'card' and not p11_cfg_bool('pay_card_enabled', true) then raise exception 'الدفع بالكارت متوقف'; end if;
  if p_method = 'wallet' and not p11_cfg_bool('pay_wallet_enabled', true) then raise exception 'الدفع بالمحفظة متوقف'; end if;
end $$;

-- ---------------------------------------------------------------- قايمة البيع (للكاشير: من غير التكلفة)
create or replace function cafe_menu() returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not (can_use_pos() or is_mgr()) then raise exception 'غير مصرح'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'name', p.name, 'price', p.price,
            'track', p.track_stock, 'stock', case when p.track_stock then p.stock end) order by p.sort, p.id)
          from cafe_products p where p.active), '[]'::jsonb);
end $$;

-- ---------------------------------------------------------------- البيع
create or replace function cafe_sell(p_items jsonb, p_method text, p_invoice bigint default null, p_note text default null)
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint; it jsonb; v_qty int; r cafe_products; v_total numeric := 0; v_method text := p_method; v_inv invoices;
begin
  if not can_use_pos() then raise exception 'غير مصرح'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'اختار منتج واحد على الأقل'; end if;
  if p_invoice is not null then
    select * into v_inv from invoices where id = p_invoice;
    if not found then raise exception 'الفاتورة مش موجودة'; end if;
    v_method := v_inv.payment_method;                    -- المشروب بيتدفع مع فاتورة الصالون بنفس الطريقة
  end if;
  perform cafe_pay_ok(v_method);
  insert into cafe_sales(invoice_id, payment_method, total, note, created_by)
    values (p_invoice, v_method, 0, nullif(btrim(coalesce(p_note,'')),''), auth.uid()) returning id into v_id;
  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := coalesce((it->>'qty')::int, 1);
    if v_qty < 1 or v_qty > 99 then raise exception 'كمية غير صحيحة'; end if;
    select * into r from cafe_products where id = (it->>'id')::bigint and active for update;
    if not found then raise exception 'منتج غير موجود أو متوقف'; end if;
    if r.track_stock then
      if r.stock < v_qty then raise exception 'المخزون مش كفاية: %', r.name; end if;
      update cafe_products set stock = stock - v_qty where id = r.id;
      insert into cafe_stock_movements(product_id, qty, reason, created_by) values (r.id, -v_qty, 'sale', auth.uid());
    end if;
    insert into cafe_sale_items(sale_id, product_id, name, qty, unit_price, unit_cost) values (v_id, r.id, r.name, v_qty, r.price, r.cost);
    v_total := v_total + r.price * v_qty;
  end loop;
  update cafe_sales set total = v_total where id = v_id;
  return v_id;
end $$;

-- دفع فاتورة الصالون مع المشروبات في عملية واحدة (دالة pos_checkout نفسها ما اتغيّرتش)
create or replace function pos_checkout_cafe(p_customer bigint, p_barber uuid, p_items jsonb, p_discount_pct numeric, p_discount_fixed numeric,
  p_method text, p_appointment bigint, p_redemption bigint, p_request bigint, p_cafe jsonb)
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_inv bigint;
begin
  v_inv := pos_checkout(p_customer, p_barber, p_items, p_discount_pct, p_discount_fixed, p_method, p_appointment, p_redemption, p_request);
  if p_cafe is not null and jsonb_typeof(p_cafe) = 'array' and jsonb_array_length(p_cafe) > 0 then
    perform cafe_sell(p_cafe, p_method, v_inv);
  end if;
  return v_inv;
end $$;

-- ---------------------------------------------------------------- إلغاء بيع
create or replace function cafe_void_sale(p_id bigint, p_reason text default null) returns void
language plpgsql security definer set search_path to 'public' as $$
declare s cafe_sales; r record;
begin
  select * into s from cafe_sales where id = p_id for update;
  if not found then raise exception 'عملية البيع مش موجودة'; end if;
  if s.status = 'void' then raise exception 'العملية دي اتلغت قبل كده'; end if;
  if not (is_mgr() or (can_use_pos() and s.created_by = auth.uid() and s.invoice_id is null and s.created_at > now() - interval '30 minutes')) then
    raise exception 'غير مصرح'; end if;
  for r in select i.product_id, i.qty from cafe_sale_items i join cafe_products p on p.id = i.product_id
            where i.sale_id = s.id and p.track_stock loop
    update cafe_products set stock = stock + r.qty where id = r.product_id;
    insert into cafe_stock_movements(product_id, qty, reason, created_by) values (r.product_id, r.qty, 'void', auth.uid());
  end loop;
  update cafe_sales set status = 'void', voided_at = now(), voided_by = auth.uid(), void_reason = nullif(btrim(coalesce(p_reason,'')),'') where id = s.id;
end $$;

-- آخر المبيعات (المدير: الكل، الكاشير: اللي هو سجّله)
create or replace function cafe_recent_sales(p_limit int default 30) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_mgr boolean := is_mgr();
begin
  if not (can_use_pos() or v_mgr) then raise exception 'غير مصرح'; end if;
  return coalesce((select jsonb_agg(x order by x.at desc) from (
    select jsonb_build_object('id', s.id, 'at', s.created_at, 'kind', case when s.invoice_id is null then 'street' else 'salon' end,
      'invoice_no', i.no, 'method', s.payment_method, 'total', s.total, 'status', s.status, 'note', s.note, 'void_reason', s.void_reason,
      'can_void', s.status = 'paid' and (v_mgr or (s.created_by = auth.uid() and s.invoice_id is null and s.created_at > now() - interval '30 minutes')),
      'items', coalesce((select jsonb_agg(jsonb_build_object('name', it.name, 'qty', it.qty, 'price', it.unit_price) order by it.id)
                           from cafe_sale_items it where it.sale_id = s.id), '[]'::jsonb)) x, s.created_at at
      from cafe_sales s left join invoices i on i.id = s.invoice_id
     where v_mgr or s.created_by = auth.uid()
     order by s.created_at desc limit greatest(least(coalesce(p_limit, 30), 200), 1)) q), '[]'::jsonb);
end $$;

-- ---------------------------------------------------------------- المنتجات والمخزون
create or replace function cafe_save_product(p_id bigint, p_name text, p_price numeric, p_cost numeric, p_track boolean, p_min int, p_active boolean, p_sort int default 0)
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint := p_id; v_name text := btrim(coalesce(p_name,''));
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if v_name = '' then raise exception 'اكتب اسم المنتج'; end if;
  if p_price is null or p_price < 0 then raise exception 'السعر غير صحيح'; end if;
  if p_cost is null or p_cost < 0 then raise exception 'التكلفة غير صحيحة'; end if;
  if coalesce(p_min, 0) < 0 then raise exception 'الحد الأدنى غير صحيح'; end if;
  if exists (select 1 from cafe_products x where lower(x.name) = lower(v_name) and x.id is distinct from p_id) then raise exception 'فيه منتج بنفس الاسم'; end if;
  if p_id is null then
    insert into cafe_products(name, price, cost, track_stock, min_stock, active, sort)
      values (v_name, p_price, p_cost, coalesce(p_track,false), coalesce(p_min,0), coalesce(p_active,true), coalesce(p_sort,0)) returning id into v_id;
  else
    update cafe_products set name = v_name, price = p_price, cost = p_cost, track_stock = coalesce(p_track,false), min_stock = coalesce(p_min,0),
           active = coalesce(p_active,true), sort = coalesce(p_sort,0) where id = p_id;
    if not found then raise exception 'المنتج مش موجود'; end if;
  end if;
  return v_id;
end $$;

create or replace function cafe_adjust_stock(p_id bigint, p_delta int, p_reason text default null) returns integer
language plpgsql security definer set search_path to 'public' as $$
declare r cafe_products;
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if p_delta is null or p_delta = 0 then raise exception 'اكتب كمية'; end if;
  select * into r from cafe_products where id = p_id for update;
  if not found then raise exception 'المنتج مش موجود'; end if;
  if not r.track_stock then raise exception 'فعّل تتبع المخزون للمنتج الأول'; end if;
  if r.stock + p_delta < 0 then raise exception 'المخزون مينفعش يبقى بالسالب'; end if;
  update cafe_products set stock = stock + p_delta where id = r.id;
  insert into cafe_stock_movements(product_id, qty, reason, created_by) values (r.id, p_delta, 'adjust:' || coalesce(nullif(btrim(p_reason),''),'تسوية'), auth.uid());
  return r.stock + p_delta;
end $$;

-- ---------------------------------------------------------------- المشتريات
-- kind = 'stock'    : بضاعة/خامات: بتتسجل مشتريات (والمخزون بيزيد لو المنتج متتبّع)، ومش مصروف (التكلفة بتتحسب وقت البيع)
-- kind = 'supplies' : مستلزمات (أكواب، سكر، أدوات): بتتسجل مصروف علطول
create or replace function cafe_record_purchase(p_date date, p_kind text, p_items jsonb, p_supplier text, p_paid_from text, p_note text, p_update_cost boolean default false)
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint; it jsonb; v_total numeric := 0; v_qty numeric; v_cost numeric; v_name text; v_pid bigint; pr cafe_products;
        v_day date := coalesce(p_date, (now() at time zone my_tz())::date);
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if p_kind not in ('stock','supplies') then raise exception 'نوع الشراء غير صحيح'; end if;
  if p_paid_from not in ('drawer','other') then raise exception 'مصدر الدفع غير صحيح'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'ضيف بند واحد على الأقل'; end if;
  insert into cafe_purchases(bought_on, kind, supplier_name, total, paid_from, note, created_by)
    values (v_day, p_kind, nullif(btrim(coalesce(p_supplier,'')),''), 1, p_paid_from, nullif(btrim(coalesce(p_note,'')),''), auth.uid()) returning id into v_id;
  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::numeric; v_cost := (it->>'unit_cost')::numeric; v_pid := nullif(it->>'product_id','')::bigint; v_name := btrim(coalesce(it->>'name',''));
    if v_qty is null or v_qty <= 0 or v_cost is null or v_cost < 0 then raise exception 'الكمية والسعر لازم أرقام صحيحة'; end if;
    if p_kind = 'stock' and v_pid is not null then
      select * into pr from cafe_products where id = v_pid for update;
      if not found then raise exception 'منتج غير موجود'; end if;
      v_name := pr.name;
      if pr.track_stock then
        if v_qty <> trunc(v_qty) then raise exception 'كمية المنتج المتتبّع لازم تكون رقم صحيح'; end if;
        update cafe_products set stock = stock + v_qty::int where id = pr.id;
        insert into cafe_stock_movements(product_id, qty, reason, created_by) values (pr.id, v_qty::int, 'restock', auth.uid());
      end if;
      if p_update_cost then update cafe_products set cost = v_cost where id = pr.id; end if;
    else
      v_pid := null;
      if v_name = '' then raise exception 'اكتب اسم كل بند'; end if;
    end if;
    insert into cafe_purchase_items(purchase_id, product_id, name, qty, unit_cost) values (v_id, v_pid, v_name, v_qty, v_cost);
    v_total := v_total + round(v_qty * v_cost, 2);
  end loop;
  if v_total <= 0 then raise exception 'إجمالي الفاتورة لازم يكون أكبر من صفر'; end if;
  update cafe_purchases set total = v_total where id = v_id;
  if p_kind = 'supplies' then
    insert into cafe_expenses(spent_on, category, amount, note, paid_from, purchase_id, created_by)
      values (v_day, 'مستلزمات', v_total, coalesce(nullif(btrim(coalesce(p_note,'')),''), 'مشتريات مستلزمات'), p_paid_from, v_id, auth.uid());
  end if;
  return v_id;
end $$;

create or replace function cafe_void_purchase(p_id bigint) returns void
language plpgsql security definer set search_path to 'public' as $$
declare p cafe_purchases; r record;
begin
  if not is_owner() then raise exception 'غير مصرح'; end if;
  select * into p from cafe_purchases where id = p_id for update;
  if not found then raise exception 'فاتورة الشراء مش موجودة'; end if;
  if p.kind = 'stock' then
    for r in select x.product_id, x.qty from cafe_purchase_items x join cafe_products c on c.id = x.product_id where x.purchase_id = p.id and c.track_stock loop
      if (select stock from cafe_products where id = r.product_id) < r.qty::int then raise exception 'مينفعش تلغي الشراء: المخزون اتباع منه'; end if;
      update cafe_products set stock = stock - r.qty::int where id = r.product_id;
      insert into cafe_stock_movements(product_id, qty, reason, created_by) values (r.product_id, -r.qty::int, 'purchase_void', auth.uid());
    end loop;
  end if;
  insert into deletion_log(table_name, row_id, row_data, extra, deleted_by)
    values ('cafe_purchases', p.id::text, to_jsonb(p), jsonb_build_object('items', (select jsonb_agg(to_jsonb(i)) from cafe_purchase_items i where i.purchase_id = p.id)), auth.uid());
  delete from cafe_purchases where id = p.id;   -- المصروف المرتبط والبنود بيتمسحوا معاها (cascade)
end $$;

-- ---------------------------------------------------------------- المصروفات
create or replace function cafe_add_expense(p_date date, p_category text, p_amount numeric, p_note text default null, p_paid_from text default 'drawer')
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint;
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'اكتب مبلغ أكبر من صفر'; end if;
  if btrim(coalesce(p_category,'')) = '' then raise exception 'اختار التصنيف'; end if;
  if p_paid_from not in ('drawer','other') then raise exception 'مصدر الدفع غير صحيح'; end if;
  insert into cafe_expenses(spent_on, category, amount, note, paid_from, created_by)
    values (coalesce(p_date, (now() at time zone my_tz())::date), btrim(p_category), p_amount, nullif(btrim(coalesce(p_note,'')),''), p_paid_from, auth.uid()) returning id into v_id;
  return v_id;
end $$;

create or replace function cafe_delete_expense(p_id bigint) returns void
language plpgsql security definer set search_path to 'public' as $$
declare e cafe_expenses;
begin
  if not is_owner() then raise exception 'غير مصرح'; end if;
  select * into e from cafe_expenses where id = p_id for update;
  if not found then raise exception 'المصروف مش موجود'; end if;
  if e.purchase_id is not null then raise exception 'المصروف ده تابع لفاتورة شراء مستلزمات. الغي فاتورة الشراء بدل ما تمسحه'; end if;
  insert into deletion_log(table_name, row_id, row_data, extra, deleted_by) values ('cafe_expenses', e.id::text, to_jsonb(e), null, auth.uid());
  delete from cafe_expenses where id = e.id;
end $$;

-- ---------------------------------------------------------------- التقارير
-- صافي الربح = مبيعات (غير الملغاة) − تكلفة المنتجات المباعة (سعر التكلفة وقت البيع) − مصروفات الكوفي.
-- المشتريات بتظهر كمؤشر لوحدها ومش بتتخصم تاني (التكلفة اتحسبت وقت البيع، ومشتريات المستلزمات اتحسبت مصروف).
create or replace function cafe_report(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_tz text := my_tz(); r jsonb;
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if p_from is null or p_to is null or p_to < p_from or p_to - p_from > 366 then raise exception 'الفترة غير صحيحة'; end if;
  with days as (select d::date as day from generate_series(p_from, p_to, interval '1 day') d),
  sd as (
    select s.id, s.invoice_id, s.payment_method, s.total, dd.day
      from cafe_sales s
      cross join lateral (select d.day from days d where p24b_in_day(s.created_at, d.day, v_tz) limit 1) dd
     where s.status = 'paid'
  ),
  it as (select i.sale_id, i.name, i.qty, i.unit_price, i.unit_cost from cafe_sale_items i where i.sale_id in (select id from sd)),
  ex as (select e.spent_on, e.category, e.amount from cafe_expenses e where e.spent_on between p_from and p_to),
  pu as (select p.bought_on, p.total, p.kind from cafe_purchases p where p.bought_on between p_from and p_to)
  select jsonb_build_object(
    'from', p_from, 'to', p_to,
    'sales',        (select coalesce(sum(total),0) from sd),
    'salon_sales',  (select coalesce(sum(total),0) from sd where invoice_id is not null),
    'street_sales', (select coalesce(sum(total),0) from sd where invoice_id is null),
    'orders',       (select count(*) from sd),
    'cogs',         (select coalesce(sum(qty * unit_cost),0) from it),
    'purchases',    (select coalesce(sum(total),0) from pu),
    'expenses',     (select coalesce(sum(amount),0) from ex),
    'net_profit',   (select coalesce(sum(total),0) from sd) - (select coalesce(sum(qty * unit_cost),0) from it) - (select coalesce(sum(amount),0) from ex),
    'by_method',    jsonb_build_object(
                      'cash',   (select coalesce(sum(total),0) from sd where payment_method = 'cash'),
                      'card',   (select coalesce(sum(total),0) from sd where payment_method = 'card'),
                      'wallet', (select coalesce(sum(total),0) from sd where payment_method = 'wallet')),
    'top', coalesce((select jsonb_agg(jsonb_build_object('name', n, 'qty', q, 'revenue', rev) order by q desc, rev desc)
                       from (select name n, sum(qty) q, sum(qty * unit_price) rev from it group by name order by sum(qty) desc, sum(qty * unit_price) desc limit 10) t), '[]'::jsonb),
    'by_day', coalesce((select jsonb_agg(jsonb_build_object('day', d.day,
                         'sales', (select coalesce(sum(total),0) from sd where sd.day = d.day),
                         'orders', (select count(*) from sd where sd.day = d.day),
                         'cogs', (select coalesce(sum(i2.qty * i2.unit_cost),0) from it i2 join sd on sd.id = i2.sale_id where sd.day = d.day),
                         'expenses', (select coalesce(sum(amount),0) from ex where ex.spent_on = d.day),
                         'purchases', (select coalesce(sum(total),0) from pu where pu.bought_on = d.day)) order by d.day) from days d), '[]'::jsonb),
    'expenses_by_category', coalesce((select jsonb_agg(jsonb_build_object('category', category, 'amount', a) order by a desc)
                       from (select category, sum(amount) a from ex group by category) t), '[]'::jsonb),
    'low_stock', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'stock', stock, 'min', min_stock) order by name)
                       from cafe_products where active and track_stock and stock <= min_stock), '[]'::jsonb)
  ) into r;
  return r;
end $$;

-- قوايم للإدارة (من غير ما نفتح الجداول للكاشير)
create or replace function cafe_admin_lists(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if p_from is null or p_to is null or p_to < p_from or p_to - p_from > 366 then raise exception 'الفترة غير صحيحة'; end if;
  return jsonb_build_object(
    'products', coalesce((select jsonb_agg(to_jsonb(p) order by p.sort, p.id) from cafe_products p), '[]'::jsonb),
    'purchases', coalesce((select jsonb_agg(jsonb_build_object('id', x.id, 'bought_on', x.bought_on, 'kind', x.kind, 'supplier', x.supplier_name, 'total', x.total,
                  'paid_from', x.paid_from, 'note', x.note, 'items', (select coalesce(jsonb_agg(jsonb_build_object('name', i.name, 'qty', i.qty, 'unit_cost', i.unit_cost) order by i.id), '[]'::jsonb) from cafe_purchase_items i where i.purchase_id = x.id)) order by x.bought_on desc, x.id desc)
                  from cafe_purchases x where x.bought_on between p_from and p_to), '[]'::jsonb),
    'expenses', coalesce((select jsonb_agg(jsonb_build_object('id', e.id, 'spent_on', e.spent_on, 'category', e.category, 'amount', e.amount, 'note', e.note,
                  'paid_from', e.paid_from, 'purchase_id', e.purchase_id) order by e.spent_on desc, e.id desc)
                  from cafe_expenses e where e.spent_on between p_from and p_to), '[]'::jsonb));
end $$;

-- ---------------------------------------------------------------- الدرج الواحد: day_figures و range_figures
-- بنغلّف الدالتين الأصليتين (من غير ما نعدّل جسمهم) ونضيف حركة الكوفي على نفس المفاتيح:
-- cash_sales/card_sales/wallet_sales/exp_cash/pur_cash. وبنضيف مفاتيح cafe_* للعرض لو احتجناها.
do $$
begin
  if to_regprocedure('day_figures_salon(date)') is null then
    alter function day_figures(date) rename to day_figures_salon;
  end if;
  if to_regprocedure('range_figures_salon(date,date)') is null then
    alter function range_figures(date, date) rename to range_figures_salon;
  end if;
end $$;

create or replace function day_figures(p_day date) returns jsonb
language plpgsql stable set search_path to 'public' as $$
declare f jsonb := day_figures_salon(p_day); v_tz text := my_tz(); cc numeric; cd numeric; cw numeric; ce numeric; cp numeric;
begin
  select coalesce(sum(total) filter (where payment_method = 'cash'),0), coalesce(sum(total) filter (where payment_method = 'card'),0),
         coalesce(sum(total) filter (where payment_method = 'wallet'),0)
    into cc, cd, cw from cafe_sales s where s.status = 'paid' and p24b_in_day(s.created_at, p_day, v_tz);
  select coalesce(sum(amount),0) into ce from cafe_expenses e where e.spent_on = p_day and e.paid_from = 'drawer' and e.purchase_id is null;
  select coalesce(sum(total),0) into cp from cafe_purchases p where p.bought_on = p_day and p.paid_from = 'drawer';
  return f || jsonb_build_object(
    'cash_sales',   (f->>'cash_sales')::numeric + cc, 'card_sales', (f->>'card_sales')::numeric + cd, 'wallet_sales', (f->>'wallet_sales')::numeric + cw,
    'exp_cash',     (f->>'exp_cash')::numeric + ce,   'pur_cash',   (f->>'pur_cash')::numeric + cp,
    'cafe_cash', cc, 'cafe_card', cd, 'cafe_wallet', cw, 'cafe_exp_cash', ce, 'cafe_pur_cash', cp);
end $$;

create or replace function range_figures(p_from date, p_to date) returns jsonb
language plpgsql stable set search_path to 'public' as $$
declare f jsonb := range_figures_salon(p_from, p_to); v_tz text := my_tz(); cc numeric; cd numeric; cw numeric; ce numeric; cp numeric;
begin
  select coalesce(sum(total) filter (where payment_method = 'cash'),0), coalesce(sum(total) filter (where payment_method = 'card'),0),
         coalesce(sum(total) filter (where payment_method = 'wallet'),0)
    into cc, cd, cw from cafe_sales s where s.status = 'paid' and (s.created_at at time zone v_tz)::date between p_from and p_to;
  select coalesce(sum(amount),0) into ce from cafe_expenses e where e.spent_on between p_from and p_to and e.paid_from = 'drawer' and e.purchase_id is null;
  select coalesce(sum(total),0) into cp from cafe_purchases p where p.bought_on between p_from and p_to and p.paid_from = 'drawer';
  return f || jsonb_build_object(
    'cash_sales',   (f->>'cash_sales')::numeric + cc, 'card_sales', (f->>'card_sales')::numeric + cd, 'wallet_sales', (f->>'wallet_sales')::numeric + cw,
    'exp_cash',     (f->>'exp_cash')::numeric + ce,   'pur_cash',   (f->>'pur_cash')::numeric + cp,
    'cafe_cash', cc, 'cafe_card', cd, 'cafe_wallet', cw, 'cafe_exp_cash', ce, 'cafe_pur_cash', cp);
end $$;

-- ---------------------------------------------------------------- ربط الكوفي بإلغاء/تأريخ فاتورة الصالون
do $$
declare d text; a1 constant text := '  insert into deletion_log(table_name, row_id, row_data, extra)';
        b1 constant text := '    update loyalty_ledger set created_at = v_new where invoice_id = p_id;';
begin
  select pg_get_functiondef(p.oid) into d from pg_proc p where p.proname = 'admin_void_invoice' and p.pronamespace = 'public'::regnamespace;
  if d is null then raise exception 'admin_void_invoice مش موجودة'; end if;
  if position('cafe_corner_void' in d) = 0 then
    if position(a1 in d) = 0 then raise exception 'مش لاقي نقطة التعديل في admin_void_invoice'; end if;
    d := replace(d, a1,
'  /* cafe_corner_void */
  update cafe_products cp set stock = cp.stock + x.q from (select i.product_id, sum(i.qty) q from cafe_sale_items i join cafe_sales s on s.id = i.sale_id
    where s.invoice_id = v_inv.id and s.status = ''paid'' group by i.product_id) x where cp.id = x.product_id and cp.track_stock;
  insert into cafe_stock_movements(product_id, qty, reason, created_by)
    select i.product_id, i.qty, ''void'', auth.uid() from cafe_sale_items i join cafe_sales s on s.id = i.sale_id
     join cafe_products cp on cp.id = i.product_id and cp.track_stock where s.invoice_id = v_inv.id and s.status = ''paid'';
  insert into deletion_log(table_name, row_id, row_data, extra)
    select ''cafe_sales'', s.id::text, to_jsonb(s), jsonb_build_object(''items'', (select jsonb_agg(to_jsonb(i)) from cafe_sale_items i where i.sale_id = s.id), ''invoice_no'', v_inv.no)
      from cafe_sales s where s.invoice_id = v_inv.id;
' || a1);
    execute d;
  end if;

  select pg_get_functiondef(p.oid) into d from pg_proc p where p.proname = 'admin_set_date' and p.pronamespace = 'public'::regnamespace;
  if d is null then raise exception 'admin_set_date مش موجودة'; end if;
  if position('cafe_corner_date' in d) = 0 then
    if position(b1 in d) = 0 then raise exception 'مش لاقي نقطة التعديل في admin_set_date'; end if;
    d := replace(d, b1, b1 || '
    /* cafe_corner_date */ update cafe_sales set created_at = v_new where invoice_id = p_id;');
    execute d;
  end if;
end $$;

