do $$
declare t text;
begin
  foreach t in array array['cafe_products','cafe_sales','cafe_sale_items','cafe_purchases','cafe_purchase_items','cafe_expenses','cafe_stock_movements'] loop
    execute format('drop policy if exists %I on %I', t || '_mgr_read', t);
    execute format('create policy %I on %I for select to authenticated using (is_mgr())', t || '_mgr_read', t);
    execute format('revoke all on %I from anon, authenticated, public', t);
    execute format('grant select on %I to authenticated', t);
  end loop;
end $$;

