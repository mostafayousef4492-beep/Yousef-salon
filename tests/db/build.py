import json,re,collections
j=json.load(open('schema.json'))
out=[]
w=out.append
w("set check_function_bodies=off;")
w("create extension if not exists pgcrypto schema extensions;" )
for e in j['enums']:
    w("create type public.%s as enum (%s);"%(e['n'],",".join("'%s'"%v for v in e['v'])))
tabs=collections.OrderedDict()
for c in j['cols']: tabs.setdefault(c['t'],[]).append(c)
seqs=set()
for t,cs in tabs.items():
    for c in cs:
        if c['df']:
            for s in re.findall(r"nextval\('([^']+)'",c['df']): seqs.add(s.split('::')[0].replace('public.',''))
for s in sorted(seqs): w("create sequence if not exists public.%s;"%s)
pk={}
for k in j['cons']:
    if k['ty']=='p': pk[k['t']]=k
for t,cs in tabs.items():
    lines=[]
    for c in cs:
        l='"%s" %s'%(c['c'],c['ty'])
        if c['gen']=='s': l+=" generated always as (%s) stored"%c['df']
        elif c['df']:
            l+=" default "+c['df']
        if c['nn']: l+=" not null"
        lines.append(l)
    w('create table public."%s" (\n  %s\n);'%(t,",\n  ".join(lines)))
# id columns without default that are pk and integer -> identity guess
for t,k in pk.items():
    m=re.match(r'PRIMARY KEY \(("?\w+"?)\)',k['d'])
    if m:
        col=m.group(1).strip('"')
        c=[x for x in tabs[t] if x['c']==col][0]
        if not c['df'] and c['ty'] in('bigint','integer'):
            w('alter table public."%s" alter column "%s" add generated by default as identity;'%(t,col))
order={'p':0,'u':1,'c':2,'f':3,'x':4}
for k in sorted(j['cons'],key=lambda k:order.get(k['ty'],5)):
    if k['t'] not in tabs: continue
    w('alter table public."%s" add constraint "%s" %s;'%(k['t'],k['n'],k['d']))
for i in j['idx']:
    if 'pkey' in i or ' UNIQUE INDEX' in i and False: pass
    w(i.replace('CREATE UNIQUE INDEX','CREATE UNIQUE INDEX IF NOT EXISTS').replace('CREATE INDEX','CREATE INDEX IF NOT EXISTS')+";")
for f in j['funcs']: w(f['d']+";")
for t in j['trg']: w(t+";")
for t in tabs: w('alter table public."%s" enable row level security;'%t)
for p in j['pol']:
    roles=",".join(p['roles'].strip('{}').split(',')) if isinstance(p['roles'],str) else ",".join(p['roles'])
    s='create policy "%s" on public."%s" for %s to %s'%(p['n'],p['t'],p['cmd'].lower() if p['cmd']!='ALL' else 'all',roles)
    if p['q']: s+=" using (%s)"%p['q']
    if p['w']: s+=" with check (%s)"%p['w']
    w(s+";")
open('schema.sql','w').write("\n".join(out))
print(len(out),"statements; seqs",seqs)
