-- ============================================================
-- ترتيب المنيو بالخيارات: قص الشعر / حلاقة الذقن / تسريح الشعر / حلاقة الأطفال
-- مبدأ الشغل: مفيش خدمة بتتوقف أو بتتمسح أو بيتغير سعرها أو اسمها (عشان الباقات والفواتير القديمة وعروض الولاء مربوطة بيها).
--   * الخدمات الشغّالة (قصة شعر / حلاقة ذقن / استشوار / استشوار+مكوه) بتبقى «خيار» جوه مجموعتها بنفس الـid والسعر.
--   * الخيارات الموقوفة المكمّلة بتتفعّل، والمكرر منها (نفس خيار موجود) بيفضل موقوف.
-- بيغيّر الأعمدة group_name / option_label / active بس. فيه نسخة احتياطية للرجوع (service_menu_backup).
-- شغّل الملف كله مرة واحدة (Ctrl+A ثم Run). آمن للتكرار.
-- ============================================================
create table if not exists public.service_menu_backup as
  select id, name, group_name, option_label, active, now() as saved_at from public.services where false;
insert into public.service_menu_backup(id, name, group_name, option_label, active)
  select s.id, s.name, s.group_name, s.option_label, s.active from public.services s
  where s.id in (1,2,6,8,30,35,36,37,38,40,41,42,45,46)
    and not exists (select 1 from public.service_menu_backup b where b.id = s.id);

update public.services s set group_name = m.g, option_label = m.l, active = m.a
from (values
  -- قص الشعر (دمج «قص شعر» و«قص الشعر» في مجموعة واحدة)
  (1 ,'قصة شعر'                              ,'قص الشعر','تدريج'                  ,true),
  (38,'قص شعر — بدون تدريج'                  ,'قص الشعر','بدون تدريج'             ,true),
  (40,'قص شعر — كلاسيك مشط ومقص'             ,'قص الشعر','كلاسيك مشط ومقص'       ,true),
  (30,'قص الشعر — استايل تدريج + قص الشعر'   ,'قص الشعر','استايل تدريج + قص الشعر' ,true),
  -- حلاقة الذقن
  (2 ,'حلاقة ذقن'                            ,'حلاقة ذقن','عادي'                  ,true),
  (35,'حلاقة ذقن — ماكينة'                   ,'حلاقة ذقن','ماكينة'                ,true),
  (36,'حلاقة ذقن — موس'                      ,'حلاقة ذقن','موس'                   ,true),
  (37,'حلاقة ذقن — تدريج'                    ,'حلاقة ذقن','تدريج'                 ,true),
  -- تسريح الشعر
  (6 ,'استشوار'                              ,'تسريح الشعر','استشوار فقط'         ,true),
  (8 ,'استشوار +مكوه'                        ,'تسريح الشعر','استشوار + مكوه'      ,true),
  (45,'تسريح الشعر — كيرلي أو ويفي'          ,'تسريح الشعر','كيرلي أو ويفي'       ,true),
  (46,'تسريح الشعر — كيرلي مكوة خصل'         ,'تسريح الشعر','كيرلي مكوة خصل'      ,true),
  -- حلاقة الأطفال
  (41,'حلاقة اطفال — حلاقة فقط'              ,'حلاقة اطفال','حلاقة فقط'           ,true),
  (42,'حلاقة اطفال — حلاقة +سشوار أو كيرلي'  ,'حلاقة اطفال','حلاقة +سشوار أو كيرلي',true)
) as m(id, nm, g, l, a)
where s.id = m.id and s.name = m.nm
  and (s.group_name is distinct from m.g or s.option_label is distinct from m.l or s.active is distinct from m.a);
