-- الخلفية: العملاء القدام كلمة سر حسابهم كانت معادلة ثابتة من الرقم ("ay-<رقم>-c9f3a1")
-- وهي ظاهرة في كود الموقع، فأي حد يعرف الرقم كان يقدر يدخل. النسخة الجديدة من التطبيق
-- بتبدّل الكلمة دي بسر عشوائي على جهاز العميل أول ما يفتح التطبيق (وهو مسجّل دخول).
--
-- ترتيب التشغيل:
--   1) ارفع النسخة الجديدة من التطبيق.
--   2) استنى كام يوم لحد ما العملاء النشطين يفتحوا التطبيق مرة (بيتبدّل لهم السر تلقائيًا).
--   3) شغّل الأمر ده مرة واحدة: بيقفل المعادلة القديمة لكل حسابات العملاء.
-- بعده: العميل اللي جهازه لسه شغّال بيفضل داخل (الجلسة بتتجدد)، واللي جلسته اتقفلت أو
-- بيدخل من جهاز جديد بياخد كود من الكاشير (زرار «إصدار كود دخول» في ملف العميل).
--
-- ملحوظة: العملاء اللي بدّلوا سرهم بالفعل (أو اللي عملوا كود دخول) بيتغيّر سرهم برضه هنا،
-- لكن جلساتهم مش بتتأثر. لو عايز تستثني حد، زوّد شرط في الـ where.
-- ============================================================================

-- عدّاد قبل التنفيذ (قراءة فقط)
select count(*) as customer_accounts
  from auth.users where email like '%@c.abu-yousef-salon.com';

