-- ============================================================================
-- موظف الكوفي كورنر: يسجّل من موبايله (بيع، مصروف، سحب من الدرج، بيع آجل + تحصيل)
-- ============================================================================
-- بيتشغّل بعد patch_coffee_corner.sql (وبعد patch_range_by_business_day.sql لو متطبّق).
-- مبادئ التصميم:
--  1) مفيش دور جديد ومفيش تعديل على enum الأدوار: الموظف حساب عادي (مساعد/كاشير...) + صلاحية perms.use_cafe.
--     الكاشير القديم بيفضل شغّال زي ما هو (من غير المفتاح، الصلاحية بتتبع use_pos).
--  2) مفيش أي تعديل على day_figures / range_figures / close_day. الدرج بيتأثر بالطرق الموجودة أصلًا:
--       - مبيعات كاش/كارت/محفظة  ← cafe_sales (زي ما هو)
--       - المصروف من الدرج        ← cafe_expenses (زي ما هو)
--       - السحب                   ← cash_moves (withdraw) أو staff_transactions (سلفة)
--       - تحصيل الآجل (كاش بس)    ← cash_moves (deposit)
--     البيع الآجل مش بيدخل الدرج لحد ما يتحصّل.
--  3) كل الكتابة من خلال دوال SECURITY DEFINER بصلاحيات متحققة جوه القاعدة. مفيش INSERT/UPDATE مباشر.
--  4) الموظف (مش المدير): اليوم = يوم العمل الحالي بس، المصروف من الدرج بس، حد أقصى للمبلغ، ممنوع بعد قفل اليوم،
--     ويتراجع عن آخر عملية له خلال 30 دقيقة بس. المدير والمالك بيشوفوا كل حاجة.
--  5) آمن للتشغيل أكتر من مرة. مفيش حذف ولا تعديل لأي بيانات موجودة.
--     دوال الكوفي اللي بتتبدّل (create or replace): cafe_menu, cafe_sell (توقيع جديد), cafe_void_sale, cafe_recent_sales,
--     cafe_add_expense, cafe_delete_expense, cafe_report — نفس الأسماء، ونفس المفاتيح اللي بترجعها + مفاتيح جديدة.
-- التراجع: drop function للدوال الجديدة + إعادة تشغيل الجزء الخاص بالدوال القديمة من patch_coffee_corner.sql،
--          والجداول الجديدة (cafe_customers, cafe_debt_payments, cafe_withdrawals) ممكن تتساب فاضية بدون ضرر.
-- ============================================================================

do $$
begin
  if to_regclass('public.cafe_sales') is null or to_regclass('public.cafe_expenses') is null then
    raise exception 'شغّل patch_coffee_corner.sql الأول';
  end if;
  if to_regclass('public.cash_moves') is null or to_regclass('public.cash_closings') is null or to_regclass('public.staff_transactions') is null then
    raise exception 'جداول الخزنة مش موجودة (cash_moves / cash_closings / staff_transactions)';
  end if;
  if to_regprocedure('public.biz_today()') is null then
    raise exception 'شغّل patch_business_day.sql الأول (biz_today)';
  end if;
end $$;

-- ---------------------------------------------------------------- الصلاحية
-- مدير/مالك: دايمًا. غير كده: لو perms.use_cafe موجودة بنحترمها (true/false)، ولو مش موجودة بنتبع use_pos (السلوك القديم).
create or replace function can_use_cafe() returns boolean
language plpgsql stable security definer set search_path to 'public' as $$
declare r text; pm jsonb;
begin
  select p.role::text, p.perms into r, pm from profiles p where p.id = auth.uid();
  if r is null then return false; end if;
  if r in ('owner','manager') then return true; end if;
  if pm is not null and pm ? 'use_cafe' then return coalesce((pm->>'use_cafe')::boolean, false); end if;
  return coalesce(can_use_pos(), false);
end $$;

-- ---------------------------------------------------------------- الجداول الجديدة
-- عملاء الآجل (مستقلين عن عملاء الصالون)
create table if not exists cafe_customers (
  id         bigint generated by default as identity primary key,
  name       text not null check (btrim(name) <> '' and char_length(name) <= 60),
  phone      text check (phone is null or phone ~ '^\+?[0-9]{6,15}$'),
  active     boolean not null default true,
  created_by uuid,
  created_at timestamptz not null default now()
);
create unique index if not exists cafe_customers_name_uq on cafe_customers (lower(btrim(name)));

-- ربط البيع الآجل بالعميل + السماح بطريقة دفع 'credit'
alter table cafe_sales add column if not exists debtor_id bigint references cafe_customers(id);
create index if not exists cafe_sales_debtor_idx on cafe_sales(debtor_id) where debtor_id is not null;

do $$
declare c record;
begin
  for c in select conname from pg_constraint
            where conrelid = 'public.cafe_sales'::regclass and contype = 'c' and conname <> 'cafe_sales_method_chk'
              and pg_get_constraintdef(oid) like '%payment_method%' loop
    execute format('alter table cafe_sales drop constraint %I', c.conname);
  end loop;
  if not exists (select 1 from pg_constraint where conname = 'cafe_sales_method_chk' and conrelid = 'public.cafe_sales'::regclass) then
    alter table cafe_sales add constraint cafe_sales_method_chk
      check (payment_method in ('cash','card','wallet','credit') and ((payment_method = 'credit') = (debtor_id is not null)));
  end if;
end $$;

