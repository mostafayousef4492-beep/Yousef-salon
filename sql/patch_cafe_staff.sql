do $$
declare f text;
begin
  foreach f in array array[
    'can_use_cafe()', 'cafe_menu()', 'cafe_sell(jsonb,text,bigint,text,bigint)', 'cafe_void_sale(bigint,text)', 'cafe_recent_sales(integer)',
    'cafe_add_expense(date,text,numeric,text,text)', 'cafe_delete_expense(bigint)', 'cafe_report(date,date)',
