-- RLS: قراءة للمدير بس، والموظف بيقرا من خلال الدوال. مفيش كتابة مباشرة.
do $$
declare t text;
begin
  foreach t in array array['cafe_customers','cafe_debt_payments','cafe_withdrawals'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists %I on %I', t || '_mgr_read', t);
    execute format('create policy %I on %I for select to authenticated using (is_mgr())', t || '_mgr_read', t);
    execute format('revoke all on %I from anon, authenticated, public', t);
    execute format('grant select on %I to authenticated', t);
    if not exists (select 1 from pg_trigger where tgrelid = ('public.' || t)::regclass and tgname = 'zz_audit') then
      execute format('create trigger zz_audit after insert or update or delete on %I for each row execute function p20_audit()', t);
    end if;
  end loop;
  foreach t in array array['cafe_debt_payments','cafe_withdrawals'] loop
    if not exists (select 1 from pg_trigger where tgrelid = ('public.' || t)::regclass and tgname = 'a0_biz_stamp') then
      execute format('create trigger a0_biz_stamp before insert on %I for each row execute function trg_biz_stamp()', t);
    end if;
  end loop;
end $$;

-- ---------------------------------------------------------------- دوال مساعدة داخلية
create or replace function cafe_debtor_balance(p_id bigint) returns numeric
language sql stable security definer set search_path to 'public' as $$
  select coalesce((select sum(total) from cafe_sales where debtor_id = p_id and status = 'paid'), 0)
       - coalesce((select sum(amount) from cafe_debt_payments where debtor_id = p_id and status = 'paid'), 0) $$;

-- ---------------------------------------------------------------- قايمة البيع / البيع / الإلغاء / آخر العمليات (بصلاحية الكوفي)
create or replace function cafe_menu() returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'name', p.name, 'price', p.price,
            'track', p.track_stock, 'stock', case when p.track_stock then p.stock end) order by p.sort, p.id)
          from cafe_products p where p.active), '[]'::jsonb);
end $$;

-- التوقيع القديم (4 باراميتر) بيتشال، والجديد ليه p_debtor بقيمة افتراضية فمفيش حاجة تتكسر (pos_checkout_cafe بينادي بـ3).
drop function if exists cafe_sell(jsonb, text, bigint, text);
create or replace function cafe_sell(p_items jsonb, p_method text, p_invoice bigint default null, p_note text default null, p_debtor bigint default null)
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint; it jsonb; v_qty int; r cafe_products; v_total numeric := 0; v_method text := p_method; v_inv invoices; v_deb_id bigint;
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'اختار منتج واحد على الأقل'; end if;
  if p_invoice is not null then
    select * into v_inv from invoices where id = p_invoice;
    if not found then raise exception 'الفاتورة مش موجودة'; end if;
    v_method := v_inv.payment_method;                    -- المشروب بيتدفع مع فاتورة الصالون بنفس الطريقة
  end if;
  if v_method = 'credit' then
    if p_invoice is not null then raise exception 'الآجل مش متاح مع فاتورة الصالون'; end if;
    if p_debtor is null then raise exception 'اختار العميل اللي هيتسجّل عليه الآجل'; end if;
    select id into v_deb_id from cafe_customers where id = p_debtor and active for update;
    if not found then raise exception 'العميل مش موجود'; end if;
  else
    perform cafe_pay_ok(v_method);
  end if;
  insert into cafe_sales(invoice_id, payment_method, total, note, created_by, debtor_id)
    values (p_invoice, v_method, 0, nullif(btrim(coalesce(p_note,'')),''), auth.uid(), v_deb_id) returning id into v_id;
  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := coalesce((it->>'qty')::int, 1);
    if v_qty < 1 or v_qty > 99 then raise exception 'كمية غير صحيحة'; end if;
    select * into r from cafe_products where id = (it->>'id')::bigint and active for update;
    if not found then raise exception 'منتج غير موجود أو متوقف'; end if;
    if r.track_stock then
      if r.stock < v_qty then raise exception 'المخزون مش كفاية: %', r.name; end if;
      update cafe_products set stock = stock - v_qty where id = r.id;
      insert into cafe_stock_movements(product_id, qty, reason, created_by) values (r.id, -v_qty, 'sale', auth.uid());
    end if;
    insert into cafe_sale_items(sale_id, product_id, name, qty, unit_price, unit_cost) values (v_id, r.id, r.name, v_qty, r.price, r.cost);
    v_total := v_total + r.price * v_qty;
  end loop;
  update cafe_sales set total = v_total where id = v_id;
  return v_id;
end $$;

create or replace function cafe_void_sale(p_id bigint, p_reason text default null) returns void
language plpgsql security definer set search_path to 'public' as $$
declare s cafe_sales; r record;
begin
  select * into s from cafe_sales where id = p_id for update;
  if not found then raise exception 'عملية البيع مش موجودة'; end if;
  if s.status = 'void' then raise exception 'العملية دي اتلغت قبل كده'; end if;
  if not (is_mgr() or (can_use_cafe() and s.created_by = auth.uid() and s.invoice_id is null and s.created_at > now() - interval '30 minutes')) then
    raise exception 'غير مصرح'; end if;
  if s.debtor_id is not null then
    perform 1 from cafe_customers where id = s.debtor_id for update;
    if cafe_debtor_balance(s.debtor_id) - s.total < 0 then
      raise exception 'العميل سدّد جزء من الآجل ده. الغي التحصيل الأول وبعدين الغي البيع'; end if;
  end if;
  for r in select i.product_id, i.qty from cafe_sale_items i join cafe_products p on p.id = i.product_id
            where i.sale_id = s.id and p.track_stock loop
    update cafe_products set stock = stock + r.qty where id = r.product_id;
    insert into cafe_stock_movements(product_id, qty, reason, created_by) values (r.product_id, r.qty, 'void', auth.uid());
  end loop;
  update cafe_sales set status = 'void', voided_at = now(), voided_by = auth.uid(), void_reason = nullif(btrim(coalesce(p_reason,'')),'') where id = s.id;
end $$;

create or replace function cafe_recent_sales(p_limit int default 30) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_mgr boolean := is_mgr();
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  return coalesce((select jsonb_agg(q.x order by q.at desc) from (
    select jsonb_build_object('id', s.id, 'at', s.created_at, 'kind', case when s.invoice_id is null then 'street' else 'salon' end,
      'invoice_no', i.no, 'method', s.payment_method, 'total', s.total, 'status', s.status, 'note', s.note, 'void_reason', s.void_reason,
      'debtor', c.name,
      'can_void', s.status = 'paid' and (v_mgr or (s.created_by = auth.uid() and s.invoice_id is null and s.created_at > now() - interval '30 minutes')),
      'items', coalesce((select jsonb_agg(jsonb_build_object('name', it.name, 'qty', it.qty, 'price', it.unit_price) order by it.id)
                           from cafe_sale_items it where it.sale_id = s.id), '[]'::jsonb)) x, s.created_at at
      from cafe_sales s left join invoices i on i.id = s.invoice_id left join cafe_customers c on c.id = s.debtor_id
     where v_mgr or s.created_by = auth.uid()
     order by s.created_at desc limit greatest(least(coalesce(p_limit, 30), 200), 1)) q), '[]'::jsonb);
end $$;

-- ---------------------------------------------------------------- المصروفات (الموظف: يوم العمل الحالي، من الدرج، بحد أقصى)
create or replace function cafe_add_expense(p_date date, p_category text, p_amount numeric, p_note text default null, p_paid_from text default 'drawer')
returns bigint language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint; v_mgr boolean := is_mgr(); v_day date;
begin
  if not (v_mgr or can_use_cafe()) then raise exception 'غير مصرح'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'اكتب مبلغ أكبر من صفر'; end if;
  if p_amount > 10000000 then raise exception 'المبلغ غير صحيح'; end if;
  if btrim(coalesce(p_category,'')) = '' or char_length(btrim(p_category)) > 60 then raise exception 'اختار التصنيف'; end if;
  if p_paid_from not in ('drawer','other') then raise exception 'مصدر الدفع غير صحيح'; end if;
  if v_mgr then
    v_day := coalesce(p_date, (now() at time zone my_tz())::date);
  else
    v_day := biz_today();
    if p_paid_from <> 'drawer' then raise exception 'مصروف الموظف بيتسجّل من الدرج بس'; end if;
    if p_amount > 100000 then raise exception 'المبلغ كبير. كلّم المالك'; end if;
    if exists (select 1 from cash_closings c where c.day = v_day) then raise exception 'اليوم اتقفل — مينفعش تسجل عمليات جديدة'; end if;
  end if;
  insert into cafe_expenses(spent_on, category, amount, note, paid_from, created_by)
    values (v_day, btrim(p_category), round(p_amount,2), nullif(btrim(coalesce(p_note,'')),''), p_paid_from, auth.uid()) returning id into v_id;
  return v_id;
end $$;

-- المالك يمسح أي مصروف. الموظف يمسح مصروفه هو خلال 30 دقيقة وقبل قفل اليوم.
create or replace function cafe_delete_expense(p_id bigint) returns void
language plpgsql security definer set search_path to 'public' as $$
declare e cafe_expenses;
begin
  select * into e from cafe_expenses where id = p_id for update;
  if not found then raise exception 'المصروف مش موجود'; end if;
  if not (is_owner() or (can_use_cafe() and e.created_by = auth.uid() and e.created_at > now() - interval '30 minutes'
                         and not exists (select 1 from cash_closings c where c.day = e.spent_on))) then
    raise exception 'غير مصرح'; end if;
  if e.purchase_id is not null then raise exception 'المصروف ده تابع لفاتورة شراء مستلزمات. الغي فاتورة الشراء بدل ما تمسحه'; end if;
  insert into deletion_log(table_name, row_id, row_data, extra, deleted_by) values ('cafe_expenses', e.id::text, to_jsonb(e), null, auth.uid());
  delete from cafe_expenses where id = e.id;
end $$;

-- ---------------------------------------------------------------- عملاء الآجل
create or replace function cafe_debtor_save(p_name text, p_phone text default null) returns bigint
language plpgsql security definer set search_path to 'public' as $$
declare v_name text := btrim(coalesce(p_name,'')); v_phone text := nullif(regexp_replace(translate(coalesce(p_phone,''), '٠١٢٣٤٥٦٧٨٩', '0123456789'), '[^0-9+]', '', 'g'), ''); v_id bigint;
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  if v_name = '' or char_length(v_name) > 60 then raise exception 'اكتب اسم العميل'; end if;
  if v_phone is not null and v_phone !~ '^\+?[0-9]{6,15}$' then raise exception 'رقم الموبايل غير صحيح'; end if;
  select id into v_id from cafe_customers where lower(btrim(name)) = lower(v_name) for update;
  if found then
    update cafe_customers set active = true, phone = coalesce(phone, v_phone) where id = v_id;
  else
    insert into cafe_customers(name, phone, created_by) values (v_name, v_phone, auth.uid()) returning id into v_id;
  end if;
  return v_id;
end $$;

-- قايمة العملاء بالمتبقي على كل واحد (التليفون للمدير بس)
create or replace function cafe_debtors() returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_mgr boolean := is_mgr();
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id', q.id, 'name', q.name, 'phone', case when v_mgr then q.phone end,
                     'balance', q.bal, 'last_at', q.last_at) order by q.bal desc, q.name)
     from (select c.id, c.name, c.phone, cafe_debtor_balance(c.id) bal,
                  greatest((select max(s.created_at) from cafe_sales s where s.debtor_id = c.id),
                           (select max(p.created_at) from cafe_debt_payments p where p.debtor_id = c.id)) last_at
             from cafe_customers c where c.active) q), '[]'::jsonb);
end $$;

-- كشف حساب عميل: بيع آجل وتحصيل بالترتيب (الأحدث الأول)
create or replace function cafe_debtor_ledger(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_mgr boolean := is_mgr(); v_me uuid := auth.uid(); c cafe_customers;
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  select * into c from cafe_customers where id = p_id;
  if not found then raise exception 'العميل مش موجود'; end if;
  return jsonb_build_object('id', c.id, 'name', c.name, 'phone', case when v_mgr then c.phone end, 'balance', cafe_debtor_balance(c.id),
    'entries', coalesce((select jsonb_agg(u.e order by u.ts desc) from (
        select z.ts, z.e from (
          select s.created_at ts, jsonb_build_object('type', 'sale', 'id', s.id, 'at', s.created_at, 'amount', s.total, 'status', s.status, 'note', s.note,
                   'can_void', s.status = 'paid' and (v_mgr or (s.created_by = v_me and s.created_at > now() - interval '30 minutes')),
                   'items', coalesce((select jsonb_agg(jsonb_build_object('name', it.name, 'qty', it.qty) order by it.id) from cafe_sale_items it where it.sale_id = s.id), '[]'::jsonb)) e
            from cafe_sales s where s.debtor_id = c.id
          union all
          select p.created_at, jsonb_build_object('type', 'pay', 'id', p.id, 'at', p.created_at, 'amount', p.amount, 'status', p.status, 'note', p.note,
                   'can_void', p.status = 'paid' and (is_owner() or (p.created_by = v_me and p.created_at > now() - interval '30 minutes')))
            from cafe_debt_payments p where p.debtor_id = c.id) z
         order by z.ts desc limit 100) u), '[]'::jsonb));
end $$;

-- تحصيل (كاش): بيتسجّل في الدرج كـ"إضافة للدرج". مينفعش تحصّل أكتر من المتبقي.
create or replace function cafe_collect_debt(p_debtor bigint, p_amount numeric, p_note text default null) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare v_name text; v_bal numeric; v_id bigint; v_mv bigint; v_day date := biz_today(); v_amt numeric := round(coalesce(p_amount, 0), 2);
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  if v_amt <= 0 or v_amt > 10000000 then raise exception 'المبلغ غير صحيح'; end if;
  select name into v_name from cafe_customers where id = p_debtor for update;
  if not found then raise exception 'العميل مش موجود'; end if;
  if exists (select 1 from cash_closings c where c.day = v_day) then raise exception 'اليوم اتقفل — مينفعش تسجل عمليات جديدة'; end if;
  v_bal := cafe_debtor_balance(p_debtor);
  if v_amt > v_bal then raise exception 'المبلغ أكبر من المتبقي على العميل (%)', v_bal; end if;
  insert into cafe_debt_payments(debtor_id, amount, note, created_by) values (p_debtor, v_amt, nullif(btrim(coalesce(p_note,'')),''), auth.uid()) returning id into v_id;
  insert into cash_moves(day, kind, amount, note) values (v_day, 'deposit', v_amt, '[كوفي] تحصيل آجل — ' || v_name) returning id into v_mv;
  update cafe_debt_payments set cash_move_id = v_mv where id = v_id;
  return jsonb_build_object('id', v_id, 'balance', v_bal - v_amt);
end $$;

create or replace function cafe_void_collection(p_id bigint) returns void
language plpgsql security definer set search_path to 'public' as $$
declare d cafe_debt_payments; m cash_moves;
begin
  select * into d from cafe_debt_payments where id = p_id for update;
  if not found then raise exception 'التحصيل مش موجود'; end if;
  if d.status = 'void' then raise exception 'التحصيل ده اتلغى قبل كده'; end if;
  if not (is_owner() or (can_use_cafe() and d.created_by = auth.uid() and d.created_at > now() - interval '30 minutes')) then
    raise exception 'غير مصرح'; end if;
  if d.cash_move_id is not null then
    select * into m from cash_moves where id = d.cash_move_id;
    if found then
      if not is_owner() and exists (select 1 from cash_closings c where c.day = m.day) then raise exception 'اليوم اتقفل. كلّم المالك'; end if;
      insert into deletion_log(table_name, row_id, row_data, extra, deleted_by) values ('cash_moves', m.id::text, to_jsonb(m), jsonb_build_object('cafe_debt_payment', d.id), auth.uid());
      delete from cash_moves where id = m.id;
    end if;
  end if;
  update cafe_debt_payments set status = 'void', voided_at = now(), voided_by = auth.uid() where id = d.id;
end $$;

-- ---------------------------------------------------------------- السحب من الدرج
create or replace function cafe_add_withdrawal(p_kind text, p_amount numeric, p_note text default null) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare v_day date := biz_today(); v_amt numeric := round(coalesce(p_amount, 0), 2); v_note text := nullif(btrim(coalesce(p_note,'')), '');
        v_name text; v_ref bigint; v_tab text; v_lbl text; v_id bigint;
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  if p_kind is null or p_kind not in ('owner','bank','advance','other') then raise exception 'اختار نوع السحب'; end if;
  if v_amt <= 0 or v_amt > 10000000 then raise exception 'المبلغ غير صحيح'; end if;
  if not is_mgr() and v_amt > 100000 then raise exception 'المبلغ كبير. كلّم المالك'; end if;
  if p_kind = 'other' and v_note is null then raise exception 'اكتب سبب السحب'; end if;
  if exists (select 1 from cash_closings c where c.day = v_day) then raise exception 'اليوم اتقفل — مينفعش تسجل عمليات جديدة'; end if;
  select full_name into v_name from profiles where id = auth.uid();
  if p_kind = 'advance' then
    if not exists (select 1 from profiles p where p.id = auth.uid() and p.role::text in ('barber','assistant','cashier','manager')) then
      raise exception 'السلفة للموظفين بس'; end if;
    insert into staff_transactions(staff_id, kind, amount, note) values (auth.uid(), 'advance', v_amt, coalesce(v_note, 'سلفة من الكوفي')) returning id into v_ref;
    v_tab := 'staff_transactions';
  else
    v_lbl := case p_kind when 'owner' then 'سحب للمالك' when 'bank' then 'إيداع بنك/محفظة' else 'سحب' end;
    insert into cash_moves(day, kind, amount, note)
      values (v_day, 'withdraw', v_amt, '[كوفي] ' || v_lbl || coalesce(' — ' || v_note, '') || coalesce(' (' || v_name || ')', '')) returning id into v_ref;
    v_tab := 'cash_moves';
  end if;
  insert into cafe_withdrawals(kind, amount, note, ref_table, ref_id, created_by) values (p_kind, v_amt, v_note, v_tab, v_ref, auth.uid()) returning id into v_id;
  return jsonb_build_object('id', v_id);
end $$;

create or replace function cafe_void_withdrawal(p_id bigint) returns void
language plpgsql security definer set search_path to 'public' as $$
declare w cafe_withdrawals; m cash_moves; t staff_transactions; v_day date;
begin
  select * into w from cafe_withdrawals where id = p_id for update;
  if not found then raise exception 'السحب مش موجود'; end if;
  if w.status = 'void' then raise exception 'السحب ده اتلغى قبل كده'; end if;
  if not (is_owner() or (can_use_cafe() and w.created_by = auth.uid() and w.created_at > now() - interval '30 minutes')) then
    raise exception 'غير مصرح'; end if;
  if w.ref_table = 'cash_moves' then
    select * into m from cash_moves where id = w.ref_id;
    if found then
      if not is_owner() and exists (select 1 from cash_closings c where c.day = m.day) then raise exception 'اليوم اتقفل. كلّم المالك'; end if;
      insert into deletion_log(table_name, row_id, row_data, extra, deleted_by) values ('cash_moves', m.id::text, to_jsonb(m), jsonb_build_object('cafe_withdrawal', w.id), auth.uid());
      delete from cash_moves where id = m.id;
    end if;
  else
    select * into t from staff_transactions where id = w.ref_id;
    if found then
      v_day := (t.created_at at time zone my_tz())::date;
      if not is_owner() and exists (select 1 from cash_closings c where c.day in (v_day, biz_today())) then raise exception 'اليوم اتقفل. كلّم المالك'; end if;
      insert into deletion_log(table_name, row_id, row_data, extra, deleted_by) values ('staff_transactions', t.id::text, to_jsonb(t), jsonb_build_object('cafe_withdrawal', w.id), auth.uid());
      delete from staff_transactions where id = t.id;
    end if;
  end if;
  update cafe_withdrawals set status = 'void', voided_at = now(), voided_by = auth.uid() where id = w.id;
end $$;

-- ---------------------------------------------------------------- حركة اليوم (الموظف: اللي سجّله هو بس. المدير: الكل)
create or replace function cafe_staff_day() returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_day date := biz_today(); v_tz text := my_tz(); v_mgr boolean := is_mgr(); v_me uuid := auth.uid(); v_own boolean := is_owner();
begin
  if not can_use_cafe() then raise exception 'غير مصرح'; end if;
  return jsonb_build_object('day', v_day, 'scope', case when v_mgr then 'all' else 'mine' end,
    'sales', (select jsonb_build_object('orders', count(*),
                'cash',   coalesce(sum(s.total) filter (where s.payment_method = 'cash'), 0),
                'card',   coalesce(sum(s.total) filter (where s.payment_method = 'card'), 0),
                'wallet', coalesce(sum(s.total) filter (where s.payment_method = 'wallet'), 0),
                'credit', coalesce(sum(s.total) filter (where s.payment_method = 'credit'), 0))
                from cafe_sales s where s.status = 'paid' and p24b_in_day(s.created_at, v_day, v_tz) and (v_mgr or s.created_by = v_me)),
    'expenses', coalesce((select jsonb_agg(jsonb_build_object('id', e.id, 'amount', e.amount, 'category', e.category, 'note', e.note, 'at', e.created_at,
                  'can_void', v_own or (e.created_by = v_me and e.created_at > now() - interval '30 minutes')) order by e.id desc)
                from cafe_expenses e where e.spent_on = v_day and e.purchase_id is null and (v_mgr or e.created_by = v_me)), '[]'::jsonb),
    'withdrawals', coalesce((select jsonb_agg(jsonb_build_object('id', w.id, 'amount', w.amount, 'kind', w.kind, 'note', w.note, 'at', w.created_at,
                  'can_void', v_own or (w.created_by = v_me and w.created_at > now() - interval '30 minutes')) order by w.id desc)
                from cafe_withdrawals w where w.status = 'ok' and p24b_in_day(w.created_at, v_day, v_tz) and (v_mgr or w.created_by = v_me)), '[]'::jsonb),
    'collections', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'amount', p.amount, 'debtor', c.name, 'note', p.note, 'at', p.created_at,
                  'can_void', v_own or (p.created_by = v_me and p.created_at > now() - interval '30 minutes')) order by p.id desc)
                from cafe_debt_payments p join cafe_customers c on c.id = p.debtor_id
               where p.status = 'paid' and p24b_in_day(p.created_at, v_day, v_tz) and (v_mgr or p.created_by = v_me)), '[]'::jsonb));
end $$;

-- ---------------------------------------------------------------- التقرير (نفس مفاتيح patch_coffee_corner + الآجل والتحصيل والسحب)
-- الآجل بيتحسب مبيعات وقت البيع (فبيدخل في صافي الربح)، والتحصيل مش إيراد تاني (بس تدفّق كاش).
create or replace function cafe_report(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare v_tz text := my_tz(); r jsonb;
begin
  if not is_mgr() then raise exception 'غير مصرح'; end if;
  if p_from is null or p_to is null or p_to < p_from or p_to - p_from > 366 then raise exception 'الفترة غير صحيحة'; end if;
  with days as (select d::date as day from generate_series(p_from, p_to, interval '1 day') d),
  sd as (
    select s.id, s.invoice_id, s.payment_method, s.total, dd.day
      from cafe_sales s
      cross join lateral (select d.day from days d where p24b_in_day(s.created_at, d.day, v_tz) limit 1) dd
     where s.status = 'paid'
  ),
  it as (select i.sale_id, i.name, i.qty, i.unit_price, i.unit_cost from cafe_sale_items i where i.sale_id in (select id from sd)),
  ex as (select e.spent_on, e.category, e.amount from cafe_expenses e where e.spent_on between p_from and p_to),
  pu as (select p.bought_on, p.total, p.kind from cafe_purchases p where p.bought_on between p_from and p_to),
  dp as (select p.amount, dd.day from cafe_debt_payments p
           cross join lateral (select d.day from days d where p24b_in_day(p.created_at, d.day, v_tz) limit 1) dd where p.status = 'paid'),
  wd as (select w.kind, w.amount, dd.day from cafe_withdrawals w
           cross join lateral (select d.day from days d where p24b_in_day(w.created_at, d.day, v_tz) limit 1) dd where w.status = 'ok')
  select jsonb_build_object(
    'from', p_from, 'to', p_to,
    'sales',        (select coalesce(sum(total),0) from sd),
    'salon_sales',  (select coalesce(sum(total),0) from sd where invoice_id is not null),
    'street_sales', (select coalesce(sum(total),0) from sd where invoice_id is null),
    'orders',       (select count(*) from sd),
    'cogs',         (select coalesce(sum(qty * unit_cost),0) from it),
    'purchases',    (select coalesce(sum(total),0) from pu),
    'expenses',     (select coalesce(sum(amount),0) from ex),
    'net_profit',   (select coalesce(sum(total),0) from sd) - (select coalesce(sum(qty * unit_cost),0) from it) - (select coalesce(sum(amount),0) from ex),
    'by_method',    jsonb_build_object(
                      'cash',   (select coalesce(sum(total),0) from sd where payment_method = 'cash'),
                      'card',   (select coalesce(sum(total),0) from sd where payment_method = 'card'),
                      'wallet', (select coalesce(sum(total),0) from sd where payment_method = 'wallet'),
                      'credit', (select coalesce(sum(total),0) from sd where payment_method = 'credit')),
    'credit_sales',   (select coalesce(sum(total),0) from sd where payment_method = 'credit'),
    'debt_collected', (select coalesce(sum(amount),0) from dp),
    'withdrawals',    (select coalesce(sum(amount),0) from wd),
    'withdrawals_by_kind', coalesce((select jsonb_agg(jsonb_build_object('kind', kind, 'amount', a) order by a desc)
                       from (select kind, sum(amount) a from wd group by kind) t), '[]'::jsonb),
    'outstanding_debt', (select coalesce(sum(b), 0) from (select cafe_debtor_balance(c.id) b from cafe_customers c) z where b > 0),
    'top_debtors', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'balance', b) order by b desc)
                       from (select c.id, c.name, cafe_debtor_balance(c.id) b from cafe_customers c) z where b > 0), '[]'::jsonb),
    'top', coalesce((select jsonb_agg(jsonb_build_object('name', n, 'qty', q, 'revenue', rev) order by q desc, rev desc)
                       from (select name n, sum(qty) q, sum(qty * unit_price) rev from it group by name order by sum(qty) desc, sum(qty * unit_price) desc limit 10) t), '[]'::jsonb),
    'by_day', coalesce((select jsonb_agg(jsonb_build_object('day', d.day,
                         'sales', (select coalesce(sum(total),0) from sd where sd.day = d.day),
                         'orders', (select count(*) from sd where sd.day = d.day),
                         'cogs', (select coalesce(sum(i2.qty * i2.unit_cost),0) from it i2 join sd on sd.id = i2.sale_id where sd.day = d.day),
                         'expenses', (select coalesce(sum(amount),0) from ex where ex.spent_on = d.day),
                         'purchases', (select coalesce(sum(total),0) from pu where pu.bought_on = d.day)) order by d.day) from days d), '[]'::jsonb),
    'expenses_by_category', coalesce((select jsonb_agg(jsonb_build_object('category', category, 'amount', a) order by a desc)
                       from (select category, sum(amount) a from ex group by category) t), '[]'::jsonb),
    'low_stock', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'stock', stock, 'min', min_stock) order by name)
                       from cafe_products where active and track_stock and stock <= min_stock), '[]'::jsonb)
  ) into r;
  return r;
end $$;

